-- 创建知识库表
CREATE TABLE IF NOT EXISTS knowledge_base (
    id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '主键ID',
    title VARCHAR(255) NOT NULL COMMENT '知识条目标题',
    category VARCHAR(100) NOT NULL COMMENT '知识分类',
    content LONGTEXT NOT NULL COMMENT '知识内容',
    keywords VARCHAR(500) COMMENT '关键词标签，用逗号分隔',
    priority INT DEFAULT 1 COMMENT '优先级（数值越大优先级越高）',
    enabled BOOLEAN DEFAULT TRUE COMMENT '是否启用',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    creator VARCHAR(100) COMMENT '创建者',
    INDEX idx_category (category),
    INDEX idx_keywords (keywords),
    INDEX idx_enabled (enabled),
    INDEX idx_priority (priority)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='知识库表';

